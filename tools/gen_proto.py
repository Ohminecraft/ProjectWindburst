#!/usr/bin/env python3
"""Generate src/proto/wbp_schema.h from protocol/wbp_schema.json (single source of truth).
The Python client reads the SAME json at run time, so firmware and app cannot drift: both carry the schema hash and the app refuses a mismatch."""
import json, sys, zlib, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(root, 'protocol/wbp_schema.json')))
def strip_desc(o):
    """The hash covers everything that changes the wire image or its meaning, not the human descriptions."""
    if isinstance(o, dict): return {k: strip_desc(v) for k, v in o.items() if k not in ('desc', 'hash', 'compat')}
    if isinstance(o, list): return [strip_desc(v) for v in o]
    return o
canon = json.dumps(strip_desc(S), sort_keys=True, separators=(',', ':')).encode()
h = zlib.crc32(canon) & 0xFFFFFFFF
if S.get('hash') != f'0x{h:08X}':
    if '--check' in sys.argv: sys.exit(f'protocol/wbp_schema.json: stored hash {S.get("hash")} != 0x{h:08X} - run tools/gen_proto.py')
    S = {'version': S['version'], 'hash': f'0x{h:08X}', **{k: v for k, v in S.items() if k not in ('version', 'hash')}}
    json.dump(S, open(os.path.join(root, 'protocol/wbp_schema.json'), 'w', newline='\n'), indent=1); open(os.path.join(root, 'protocol/wbp_schema.json'), 'a', newline='\n').write('\n')
CT = {'u8': 'uint8_t', 'bool': 'uint8_t', 'u16': 'uint16_t', 'u32': 'uint32_t', 'i16': 'int16_t', 'i32': 'int32_t', 'f32': 'float'}
SZ = {'u8': 1, 'bool': 1, 'u16': 2, 'u32': 4, 'i16': 2, 'i32': 4, 'f32': 4}
enum_size = {k: len(v) for k, v in S['enums'].items()}

def compat_of(sec):
    """'compat' in the schema: one older size, or a list of them (newest first; at most four)."""
    c = sec.get('compat', 0); c = list(c) if isinstance(c, list) else [c]
    assert len(c) <= 4, f'section {sec["name"]}: at most four older sizes'
    return [int(x) for x in c] + [0] * (4 - len(c))

def role_of(x):
    r = x.get('role', 'rx'); assert r in ('rx', 'tx'), f'{x["name"]}: role is rx or tx'
    return 0 if r == 'rx' else 1

def lit(t, v):
    if t == 'f32': return repr(float(v)) + 'f' if '.' in repr(float(v)) or 'e' in repr(float(v)) else repr(float(v)) + '.0f'
    if t == 'u32': return f'{int(v)}u'
    return str(int(v))

o = []
w = o.append
w('// GENERATED by tools/gen_proto.py from protocol/wbp_schema.json - DO NOT EDIT.')
w('#pragma once')
w('#include <stdint.h>')
w('#include <stddef.h>')
w('#include <string.h>')
w('')
w('// Windburst protocol schema: settings sections, telemetry streams, commands. Layouts are packed little-endian (the ESP32 is little-endian,')
w('// so a struct is its own wire image). The Python client builds the same layouts from the same json.')
w('namespace wbp {')
w(f'constexpr uint8_t kProtocolVersion = {S["version"]};')
w(f'constexpr uint32_t kSchemaHash = 0x{h:08X}u;')
w('')
w('enum Err : uint8_t { ' + ', '.join(f'ERR_{e}' for e in S['errors']) + ' };')
w('enum Cmd : uint8_t { ' + ', '.join(f'CMD_{c["name"]} = {c["id"]}' for c in S['commands']) + ' };')
w('enum SectionId : uint8_t { ' + ', '.join(f'SEC_{s["name"].upper()} = {s["id"]}' for s in S['sections']) + ' };')
w('enum StreamId : uint8_t { ' + ', '.join(f'STR_{s["name"].upper()} = {s["id"]}' for s in S['streams']) + ' };')
for ename, vals in S['enums'].items():
    w(f'enum {ename.upper()}_E : uint8_t {{ ' + ', '.join(f'{ename.upper()}_{v}' for v in vals) + ' };')
for bname, vals in S.get('bits', {}).items():
    w(f'enum {bname.upper()}_B : uint32_t {{ ' + ', '.join(f'{bname.upper()}_{v} = 1u << {i}' for i, v in enumerate(vals)) + ' };')
w('')
def field_decl(f):
    c = CT[f['t']]; cnt = f.get('count')
    return f'{c} {f["n"]}' + (f'[{cnt}]' if cnt else '') + ';'
def size_of(fields): return sum(SZ[f['t']] * (f.get('count') or 1) for f in fields)

for sec in S['sections']:
    n = sec['name']
    w(f'struct __attribute__((packed)) S_{n} {{')
    for f in sec['fields']: w('    ' + field_decl(f))
    w('};')
    w(f'static_assert(sizeof(S_{n}) == {size_of(sec["fields"])}, "S_{n} layout");')
    # defaults
    w(f'inline void defaults(S_{n}& s) {{')
    for f in sec['fields']:
        cnt = f.get('count'); d = f['d']
        if cnt:
            vals = d if isinstance(d, list) else [d] * cnt
            for i, v in enumerate(vals): w(f'    s.{f["n"]}[{i}] = {lit(f["t"], v)};')
        else: w(f'    s.{f["n"]} = {lit(f["t"], d)};')
    w('}')
    # validation: clamp ranges, enum bounds, bools. returns number of fields changed.
    w(f'inline int validate(S_{n}& s) {{')
    w('    int fixed = 0; (void)s;')
    for f in sec['fields']:
        t = f['t']; cnt = f.get('count'); nm = f['n']
        rng = []
        if t == 'bool': rng = ('0', '1')
        elif 'enum' in f: rng = ('0', str(enum_size[f['enum']] - 1))
        elif 'min' in f and 'max' in f: rng = (lit(t, f['min']), lit(t, f['max']))
        if not rng:
            if t == 'f32': sys.exit(f'{n}.{nm}: every float setting needs min and max (NaN / garbage protection)')
            continue
        loop = f'for (int i = 0; i < {cnt}; i++) ' if cnt else ''
        ref = f's.{nm}[i]' if cnt else f's.{nm}'
        tmax = {'u8': 255, 'bool': 255, 'u16': 65535, 'u32': 4294967295}.get(t)
        lo_needed = not (t in ('u8', 'bool', 'u16', 'u32') and int(float(rng[0].rstrip('uf'))) == 0)
        hi_needed = not (tmax is not None and int(float(rng[1].rstrip('uf'))) >= tmax)
        parts = []
        if t == 'f32':                                       # NaN compares false with everything: it would slip through a range check
            d = f['d']; dv = (d if isinstance(d, list) else [d] * (cnt or 1))
            if cnt: w(f'    {{ static const float dflt[{cnt}] = {{' + ', '.join(lit('f32', v) for v in dv) + '}; ' + f'for (int i = 0; i < {cnt}; i++) if (!({ref} == {ref})) {{ {ref} = dflt[i]; fixed++; }} }}')
            else: w(f'    if (!({ref} == {ref})) {{ {ref} = {lit("f32", dv[0])}; fixed++; }}')
        opt = f' && {ref} != 255' if f.get('optional') else ''   # 255 = "none" for an optional enum slot
        if lo_needed: parts.append(f'if ({ref} < {rng[0]}) {{ {ref} = {rng[0]}; fixed++; }}')
        # (an optional slot with a value nobody knows becomes "none", not the last entry of the list: an unknown mode must not
        #  turn into whichever mode happens to be the newest)
        if hi_needed: parts.append(('else ' if lo_needed else '') + f'if ({ref} > {rng[1]}{opt}) {{ {ref} = {"255" if f.get("optional") else rng[1]}; fixed++; }}')
        if parts: w(f'    {loop}{{ ' + ' '.join(parts) + ' }')
    w('    return fixed;')
    w('}')
    w('')
w('struct Settings {')
for sec in S['sections']: w(f'    S_{sec["name"]} {sec["name"]};')
w('};')
w('inline void defaults(Settings& s) { ' + ' '.join(f'defaults(s.{sec["name"]});' for sec in S['sections']) + ' }')
w('')
w('// live: applied to the running firmware without a reboot. compat .. compat4: sizes of this section in older firmwares whose layout was the same\n// up to that size (fields were only appended or cut at the end since): such a stored record is still loaded. 0 = none.')
w('// role: the device that has the section (ROLE_RX = 0 the flight controller, ROLE_TX = 1 the transmitter; "role" in the schema, absent = rx).\n// One schema for both: a server serves, and a store keeps, only the sections of its own role.')
w('struct SectionInfo { uint8_t id; const char* name; uint16_t size; bool live; uint16_t compat, compat2, compat3, compat4; uint8_t role; };')
w(f'constexpr int kSectionCount = {len(S["sections"])};')
w('constexpr SectionInfo kSections[kSectionCount] = {' + ', '.join(f'{{SEC_{s["name"].upper()}, "{s["name"]}", {size_of(s["fields"])}, {"true" if s.get("live") else "false"}, {compat_of(s)[0]}, {compat_of(s)[1]}, {compat_of(s)[2]}, {compat_of(s)[3]}, {role_of(s)}}}' for s in S['sections']) + '};')
w('inline const SectionInfo* find_section(uint8_t id) { for (const auto& s : kSections) if (s.id == id) return &s; return nullptr; }')
w('// pointer to / size of a section inside a Settings object (nullptr if unknown)')
w('inline uint8_t* section_ptr(Settings& st, uint8_t id) { switch (id) {')
for sec in S['sections']: w(f'    case SEC_{sec["name"].upper()}: return (uint8_t*)&st.{sec["name"]};')
w('    default: return nullptr; } }')
w('inline int validate_section(Settings& st, uint8_t id) { switch (id) {')
for sec in S['sections']: w(f'    case SEC_{sec["name"].upper()}: return validate(st.{sec["name"]});')
w('    default: return -1; } }')
w('inline bool defaults_section(Settings& st, uint8_t id) { switch (id) {')
for sec in S['sections']: w(f'    case SEC_{sec["name"].upper()}: defaults(st.{sec["name"]}); return true;')
w('    default: return false; } }')
w('')
w('// ---- telemetry streams ----')
for st in S['streams']:
    n = st['name']
    w(f'struct __attribute__((packed)) T_{n} {{')
    for f in st['fields']: w('    ' + field_decl(f))
    w('};')
    w(f'static_assert(sizeof(T_{n}) == {size_of(st["fields"])}, "T_{n} layout");')
w('// ---- commands ----')
w('struct CommandInfo { uint8_t id; const char* name; uint8_t arg_bytes; bool armed_ok; uint8_t writes_section; };   // writes_section: section the command changes in RAM (0 = none)')
w(f'constexpr int kCommandCount = {len(S["commands"])};')
sec_id = {s['name']: s['id'] for s in S['sections']}
w('constexpr CommandInfo kCommands[kCommandCount] = {' + ', '.join(
    f'{{CMD_{c["name"]}, "{c["name"]}", {sum(SZ[a["t"]] for a in c["args"])}, {"true" if c.get("armed_ok") else "false"}, {sec_id[c["writes"]] if c.get("writes") else 0}}}' for c in S['commands']) + '};')
w('inline const CommandInfo* find_command(uint8_t id) { for (const auto& c : kCommands) if (c.id == id) return &c; return nullptr; }')
w('// wire value * scale = engineering value (the client applies the same numbers from the json)')
w('namespace scale {')
for st in S['streams']:
    for f in st['fields']:
        if 'scale' in f: w(f'constexpr float {st["name"]}_{f["n"]} = {lit("f32", f["scale"])};')
w('} // namespace scale')
w('struct StreamInfo { uint8_t id; const char* name; uint16_t size; uint16_t default_rate; uint16_t max_rate; uint8_t role; };')
w(f'constexpr int kStreamCount = {len(S["streams"])};')
w('constexpr StreamInfo kStreams[kStreamCount] = {' + ', '.join(f'{{STR_{s["name"].upper()}, "{s["name"]}", {size_of(s["fields"])}, {s["rate"]}, {s["max"]}, {role_of(s)}}}' for s in S['streams']) + '};')
w('inline const StreamInfo* find_stream(uint8_t id) { for (const auto& s : kStreams) if (s.id == id) return &s; return nullptr; }')
w('} // namespace wbp')
open(os.path.join(root, 'src/proto/wbp_schema.h'), 'w', newline='\n').write('\n'.join(o) + '\n')

# ---- the field table of the settings, for the CLI (src/app/cli.h): names, places, types, ranges, enum / bit names
q = ['// Generated by tools/gen_proto.py from protocol/wbp_schema.json - do not edit.', '// Every settings field by name: what the CLI (src/app/cli.h) reads and writes. Only the CLI includes this (the strings cost flash).',
     '#pragma once', '#include "wbp_schema.h"', 'namespace wbp {',
     'enum FieldType : uint8_t { FT_U8, FT_BOOL, FT_U16, FT_U32, FT_I16, FT_I32, FT_F32 };',
     'enum FieldFlag : uint8_t { FF_TEXT = 1, FF_OPTIONAL = 4, FF_RANGE = 8, FF_BITS = 16 };',
     'struct FieldInfo { uint8_t section; const char* name; uint16_t offset; uint8_t type, count, flags; float scale, min, max; const char* const* names; uint8_t n_names; };']
FT = {'u8': 'FT_U8', 'bool': 'FT_BOOL', 'u16': 'FT_U16', 'u32': 'FT_U32', 'i16': 'FT_I16', 'i32': 'FT_I32', 'f32': 'FT_F32'}
lists = {}
for kind in ('enums', 'bits'):
    for k, v in S[kind].items():
        nm = f'k{kind[0].upper()}_{k}'; lists[(kind, k)] = (nm, len(v))
        q.append(f'static const char* const {nm}[] = {{' + ', '.join(f'"{x}"' for x in v) + '};')
rows = []
for sec in S['sections']:
    off = 0
    for f in sec['fields']:
        fl = []
        if f.get('text'): fl.append('FF_TEXT')
        if f.get('optional'): fl.append('FF_OPTIONAL')
        if 'min' in f and 'max' in f: fl.append('FF_RANGE')
        names, nn = 'nullptr', 0
        if 'enum' in f: names, nn = lists[('enums', f['enum'])]
        if 'bits' in f: names, nn = lists.get(('bits', f['bits'])) or lists[('enums', f['bits'])]; fl.append('FF_BITS')
        rows.append(f'    {{SEC_{sec["name"].upper()}, "{f["n"]}", {off}, {FT[f["t"]]}, {f.get("count") or 1}, {"|".join(fl) or 0}, {lit("f32", f.get("scale", 1))}, {lit("f32", f.get("min", 0))}, {lit("f32", f.get("max", 0))}, {names}, {nn}}},')
        off += SZ[f['t']] * (f.get('count') or 1)
q.append(f'constexpr int kFieldCount = {len(rows)};')
q.append('static const FieldInfo kFields[kFieldCount] = {'); q += rows; q.append('};')
q.append('} // namespace wbp')
open(os.path.join(root, 'src/proto/wbp_fields.h'), 'w', newline='\n').write('\n'.join(q) + '\n')
print('schema hash 0x%08X' % h, 'sections', len(S['sections']), 'streams', len(S['streams']))
